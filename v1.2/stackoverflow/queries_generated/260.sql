select
    tq.Id as QuestionId,
    tq.Title,
    coalesce(tq.Tags, '') as Tags,
    tq.Score,
    tq.ViewCount,
    tq.AnswerCount,
    tq.FavoriteCount,
    tq.ClosedDate,
    tq.LastActivityDate,
    u.DisplayName as OwnerName,
    u.Reputation as OwnerReputation,
    ubc.GoldBadges,
    ubc.SilverBadges,
    ubc.BronzeBadges,
    phc.CloseReasonName,
    phc.CloseDate,
    (select count(*) from Comments c where c.PostId = tq.Id and c.CreationDate > tq.CreationDate) as CommentCountAfterCreation,
    (select string_agg(distinct vt.Name, ', ') from Votes v join VoteTypes vt on vt.Id = v.VoteTypeId where v.PostId = tq.Id) as VoteTypesOnQuestion,
    (select avg(a.Score) from Posts a where a.ParentId = tq.Id and a.PostTypeId = 2) as AvgAnswerScore,
    (select max(a.Score) from Posts a where a.ParentId = tq.Id and a.PostTypeId = 2) as MaxAnswerScore,
    row_number() over (order by tq.Score desc, tq.ViewCount desc) as RankByScoreView,
    dense_rank() over (partition by u.Location order by u.Reputation desc) as UserLocationRank,
    case when tq.ClosedDate is null then 'Open' else 'Closed' end as PostStatus,
    case
        when tq.Score > 100 then 'High Score'
        when tq.Score between 50 and 100 then 'Medium Score'
        else 'Low Score'
    end as ScoreCategory,
    regexp_replace(coalesce(tq.Tags, ''), '[<>]', '', 'g') as CleanTags,
    concat('Question: ', tq.Title, ' [Score: ', tq.Score::text, ']') as QuestionSummary
from TopQuestionsWithCloseInfo tq
left join Users u on u.Id = tq.OwnerUserId
left join (
    select
        UserId,
        sum(case when Class = 1 then BadgeCount else 0 end) as GoldBadges,
        sum(case when Class = 2 then BadgeCount else 0 end) as SilverBadges,
        sum(case when Class = 3 then BadgeCount else 0 end) as BronzeBadges
    from UserBadgeCounts
    group by UserId
) ubc on ubc.UserId = u.Id
left join PostCloseReasons phc on phc.PostId = tq.Id
where u.Reputation > 1000 or tq.FavoriteCount > 5
order by RankByScoreView
limit 50;