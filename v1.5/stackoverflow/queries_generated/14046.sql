WITH cte AS (
    SELECT 
        p.Id AS PostId,
        p.Title,
        p.Body,
        p.CreationDate,
        p.OwnerUserId,
        p.PostTypeId,
        p.Tags,
        p.AnswerCount,
        p.CommentCount,
        p.FavoriteCount,
        p.ClosedDate,
        p.CommunityOwnedDate,
        u.DisplayName AS OwnerDisplayName,
        u.Reputation,
        u.CreationDate AS UserCreationDate,
        u.LastAccessDate,
        u.WebsiteUrl,
        u.Location,
        u.AboutMe,
        u.Views,
        u.UpVotes,
        u.DownVotes,
        u.ProfileImageUrl,
        u.EmailHash,
        u.AccountId,
        b.Id AS BadgeId,
        b.Name AS BadgeName,
        b.Date AS BadgeDate,
        b.Class AS BadgeClass,
        b.TagBased AS IsBadgeTagBased,
        CASE WHEN p.ClosedDate IS NOT NULL THEN c.Name ELSE NULL END AS CloseReason,
        CASE WHEN p.CommunityOwnedDate IS NOT NULL THEN 'Community Owned' ELSE NULL END AS CommunityOwned,
        STRING_AGG(DISTINCT pt.Name, ', ') AS PostTypeNames,
        STRING_AGG(DISTINCT lt.Name, ', ') AS LinkTypeNames,
        STRING_AGG(DISTINCT vt.Name, ', ') AS VoteTypeNames
    FROM Posts p
    LEFT JOIN Users u ON p.OwnerUserId = u.Id
    LEFT JOIN Badges b ON u.Id = b.UserId
    LEFT JOIN CloseReasonTypes c ON CAST(ph.Comment AS INT) = c.Id
    LEFT JOIN PostHistory ph ON p.Id = ph.PostId AND ph.PostHistoryTypeId = 10
    LEFT JOIN PostTypes pt ON p.PostTypeId = pt.Id
    LEFT JOIN PostLinks pl ON p.Id = pl.PostId
    LEFT JOIN LinkTypes lt ON pl.LinkTypeId = lt.Id
    LEFT JOIN Votes v ON p.Id = v.PostId
    LEFT JOIN VoteTypes vt ON v.VoteTypeId = vt.Id
    GROUP BY
        p.Id,
        p.Title,
        p.Body,
        p.CreationDate,
        p.OwnerUserId,
        p.PostTypeId,
        p.Tags,
        p.AnswerCount,
        p.CommentCount,
        p.FavoriteCount,
        p.ClosedDate,
        p.CommunityOwnedDate,
        u.DisplayName,
        u.Reputation,
        u.CreationDate,
        u.LastAccessDate,
        u.WebsiteUrl,
        u.Location,
        u.AboutMe,
        u.Views,
        u.UpVotes,
        u.DownVotes,
        u.ProfileImageUrl,
        u.EmailHash,
        u.AccountId,
        b.Id,
        b.Name,
        b.Date,
        b.Class,
        b.TagBased,
        c.Name,
        ph.Comment
)
SELECT 
    PostId,
    Title,
    Body,
    CreationDate,
    OwnerUserId,
    PostTypeId,
    Tags,
    AnswerCount,
    CommentCount,
    FavoriteCount,
    ClosedDate,
    CommunityOwnedDate,
    OwnerDisplayName,
    Reputation,
    UserCreationDate,
    LastAccessDate,
    WebsiteUrl,
    Location,
    AboutMe,
    Views,
    UpVotes,
    DownVotes,
    ProfileImageUrl,
    EmailHash,
    AccountId,
    BadgeId,
    BadgeName,
    BadgeDate,
    BadgeClass,
    IsBadgeTagBased,
    CloseReason,
    CommunityOwned,
    PostTypeNames,
    LinkTypeNames,
    VoteTypeNames,
    (SELECT COUNT(*) FROM Comments WHERE PostId = cte.PostId) AS CommentCount,
    (SELECT COUNT(*) FROM Votes WHERE PostId = cte.PostId AND VoteTypeId = 2) AS UpVoteCount,
    (SELECT COUNT(*) FROM Votes WHERE PostId = cte.PostId AND VoteTypeId = 3) AS DownVoteCount,
    (SELECT COUNT(*) FROM Votes WHERE PostId = cte.PostId AND VoteTypeId = 5) AS FavoriteCount,
    (SELECT COUNT(*) FROM PostLinks WHERE PostId = cte.PostId AND LinkTypeId = 1) AS LinkedPostCount,
    (SELECT COUNT(*) FROM PostLinks WHERE PostId = cte.PostId AND LinkTypeId = 3) AS DuplicatePostCount,
    (SELECT COUNT(*) FROM PostHistory WHERE PostId = cte.PostId AND PostHistoryTypeId = 10) AS ClosureVoteCount,
    (SELECT COUNT(*) FROM PostHistory WHERE PostId = cte.PostId AND PostHistoryTypeId = 11) AS ReopenVoteCount,
    (SELECT COUNT(*) FROM PostHistory WHERE PostId = cte.PostId AND PostHistoryTypeId = 12) AS DeletionVoteCount,
    (SELECT COUNT(*) FROM PostHistory WHERE PostId = cte.PostId AND PostHistoryTypeId = 13) AS UndeletionVoteCount,
    (SELECT COUNT(*) FROM PostHistory WHERE PostId = cte.PostId AND PostHistoryTypeId = 14) AS LockVoteCount,
    (SELECT COUNT(*) FROM PostHistory WHERE PostId = cte.PostId AND PostHistoryTypeId = 15) AS UnlockVoteCount,
    (SELECT COUNT(*) FROM PostHistory WHERE PostId = cte.PostId AND PostHistoryTypeId = 19) AS ProtectionVoteCount,
    (SELECT COUNT(*) FROM PostHistory WHERE PostId = cte.PostId AND PostHistoryTypeId = 20) AS UnprotectionVoteCount
FROM cte;